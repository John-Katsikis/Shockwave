#!/usr/bin/env python3
"""Writes Scenes/physics-stress-<N>.swscene: N dynamic boxes and spheres dropped into a
walled pit, plus a crate tower and a few fast continuous-collision balls. A third of the
bodies are spheres, which keep rolling, so the pile never falls asleep: the worst case.
--boxes writes Scenes/physics-stress-boxes-<N>.swscene instead, all boxes, which settles
and sleeps within a few seconds.

    python3 Games/Sample/Tools/MakePhysicsStress.py                  # 500 1000 2000 4000
    python3 Games/Sample/Tools/MakePhysicsStress.py 3000 5000        # any counts
    python3 Games/Sample/Tools/MakePhysicsStress.py --boxes 1000 4000

Benchmark one with:
    build/bin/player --project Games/Sample/Sample.swproject \\
        --scene Games/Sample/Scenes/physics-stress-2000.swscene \\
        --benchmark 20 --vsync off --fps 0 --json out.json
"""

import pathlib
import random
import sys

SCENES = pathlib.Path(__file__).resolve().parent.parent / "Scenes"
PIT = 24.0      # inner width of the pit, metres
WALL = 14.0     # wall height
SPACING = 1.1   # spawn lattice spacing; bodies are 0.8 m across


def entity(name, *components):
    lines = [f'entity "{name}"']
    for component in components:
        lines.append(f"  {component[0]}")
        lines += [f"    {field}" for field in component[1:]]
    return "\n".join(lines + ["end", ""])


def box(name, position, scale, tint, texture="grid"):
    return entity(
        name,
        ("Transform", f"position {position[0]:g} {position[1]:g} {position[2]:g}",
         f"scale {scale[0]:g} {scale[1]:g} {scale[2]:g}"),
        ("MeshRenderer", "mesh cube", f"texture {texture}", f"tint {tint}"),
        ("Collider", "shape Box"),
        ("RigidBody", "motion Static"))


def scene(count, boxes_only=False):
    rng = random.Random(count)
    out = [
        "shockwave_scene 2",
        "",
        f"# Physics stress test: {count} dynamic {'boxes' if boxes_only else 'bodies'} falling into a walled pit, a ten-crate",
        "# tower and four 60 m/s continuous-collision balls. Generated by",
        "# Tools/MakePhysicsStress.py; regenerate rather than editing by hand.",
        "",
        entity("Environment",
               ("Environment", "sky_color 0.3 0.38 0.5 1", "ground_color 0.06 0.07 0.09 1",
                "shadow_distance 90"),
               ("PhysicsSettings", "gravity 0 -9.81 0", "collision_steps 1")),
        entity("Main Camera",
               ("Transform", "position 0 30 42", "rotation -34 0 0"),
               ("Camera", "fov 60", "near_plane 0.1", "primary 1")),
        entity("Sun",
               ("Transform", "position 0 30 0", "rotation -55 -30 0"),
               ("Light", "type Directional", "intensity 2.6")),
        box("Floor", (0, -0.25, 0), (80, 0.5, 80), "0.42 0.46 0.52 1"),
    ]
    half = PIT / 2 + 0.25
    for name, position, scale in [
        ("Wall north", (0, WALL / 2, -half), (PIT + 1, WALL, 0.5)),
        ("Wall south", (0, WALL / 2, half), (PIT + 1, WALL, 0.5)),
        ("Wall west", (-half, WALL / 2, 0), (0.5, WALL, PIT)),
        ("Wall east", (half, WALL / 2, 0), (0.5, WALL, PIT)),
    ]:
        out.append(box(name, position, scale, "0.55 0.6 0.68 1", "panel"))

    # Spawn lattice: fills layers of the pit from 2 m up, so everything lands at once-ish.
    side = int((PIT - 1) / SPACING)
    start = -(side - 1) * SPACING / 2
    for i in range(count):
        layer, cell = divmod(i, side * side)
        x = start + (cell % side) * SPACING + rng.uniform(-0.1, 0.1)
        z = start + (cell // side) * SPACING + rng.uniform(-0.1, 0.1)
        y = 2 + layer * SPACING
        rotation = " ".join(f"{rng.uniform(0, 90):.0f}" for _ in range(3))
        hue = [(1, 0.5, 0.2), (0.35, 0.65, 1), (0.4, 0.85, 0.45), (0.9, 0.85, 0.3)][i % 4]
        tint = f"{hue[0]} {hue[1]} {hue[2]} 1"
        transform = ("Transform", f"position {x:.2f} {y:.2f} {z:.2f}", f"rotation {rotation}",
                     "scale 0.8 0.8 0.8")
        body = ("RigidBody", "motion Dynamic", "friction 0.6", "restitution 0.1")
        if not boxes_only and i % 3 == 2:
            out.append(entity(f"Ball {i}", transform,
                              ("MeshRenderer", "mesh sphere", "texture checker", f"tint {tint}"),
                              ("Collider", "shape Sphere", "radius 0.5"), body))
        else:
            out.append(entity(f"Crate {i}", transform,
                              ("MeshRenderer", "mesh cube", "texture panel", f"tint {tint}"),
                              ("Collider", "shape Box"), body))

    # A tower outside the pit: stacking stability under load.
    for level in range(10):
        out.append(entity(
            f"Tower crate {level}",
            ("Transform", f"position 18 {0.5 + level * 1.0:.2f} 0"),
            ("MeshRenderer", "mesh cube", "texture panel", "tint 1 0.5 0.2 1"),
            ("Collider", "shape Box"),
            ("RigidBody", "motion Dynamic", "mass 2", "friction 0.8")))

    # Fast continuous balls fired at the pit walls: these must not tunnel through.
    for k, (px, pz, vx, vz) in enumerate([(-30, -6, 60, 0), (30, 6, -60, 0), (-6, -30, 0, 60), (6, 30, 0, -60)]):
        out.append(entity(
            f"Fast ball {k}",
            ("Transform", f"position {px} 3 {pz}", "scale 0.3 0.3 0.3"),
            ("MeshRenderer", "mesh sphere", "tint 1 0.3 0.3 1"),
            ("Collider", "shape Sphere", "radius 0.5"),
            ("RigidBody", "motion Dynamic", "mass 0.5", "gravity_factor 0", f"linear_velocity {vx} 0 {vz}",
             "continuous 1")))
    return "\n".join(out)


def main():
    args = sys.argv[1:]
    boxes_only = "--boxes" in args
    counts = [int(arg) for arg in args if arg != "--boxes"] or [500, 1000, 2000, 4000]
    for count in counts:
        path = SCENES / f"physics-stress-{'boxes-' if boxes_only else ''}{count}.swscene"
        path.write_text(scene(count, boxes_only))
        print(path)


if __name__ == "__main__":
    main()
