#!/usr/bin/env python3
"""Prepare local library assets and reproducible RenderLab scenes. Never edits sources."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess

from PIL import Image, ImageOps

PROJECT = Path(__file__).resolve().parents[1]
GUNS = [1, 6, 10, 14, 18, 22, 26, 30]
ENGINES = ['jro_engine_001', 'jro_engine_004', 'jro_engine_008', 'jro_engine_012',
           'jro_jetengine_003', 'jro_jetengine_009', 'jro_rocketengine_004', 'jro_thrustengine_008']


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def prepare_maps(folder, dest, size, flip):
    maps = folder / 'maps'
    names = ['BaseColor', 'Normal', 'Roughness', 'Metalness']
    sources = {}
    for name in names:
        matches = sorted(p for p in maps.glob('*.png') if f'_{name}.' in p.name)
        if len(matches) != 1:
            raise ValueError(f'{maps}: expected one {name} map; found {len(matches)}')
        sources[name] = matches[0]
    def read(name, mode):
        with Image.open(sources[name]) as original:
            image = original.convert(mode)
        if size:
            image.thumbnail((size, size), Image.Resampling.LANCZOS)
        return image
    base, normal = read('BaseColor', 'RGB'), read('Normal', 'RGB')
    if flip:
        r, g, b = normal.split()
        normal = Image.merge('RGB', (r, ImageOps.invert(g), b))
    rough, metal = read('Roughness', 'L'), read('Metalness', 'L')
    if rough.size != metal.size:
        raise ValueError(f'{maps}: metallic and roughness maps have different dimensions')
    base.save(dest / 'basecolor.png')
    normal.save(dest / 'normal.png')
    # Standard glTF: green roughness, blue metallic; red unused (white).
    Image.merge('RGB', (Image.new('L', rough.size, 255), rough, metal)).save(dest / 'metallic-roughness.png')
    return {name: {'path': str(path), 'sha256': digest(path)} for name, path in sources.items()}


def entity(name, components):
    return f'entity "{name}"\n{components}end\n\n'


def write_prefab(asset):
    low, high = asset['min'], asset['max']
    scale = 3.2 / max(b-a for a, b in zip(low, high))
    center = [(a+b)/2 for a, b in zip(low, high)]
    offset = [-center[0]*scale, 0.55-low[1]*scale, -center[2]*scale]
    s = 'shockwave_prefab 1\n\n'
    s += entity('Display', '  Transform\n')
    s += entity('Model', f'  Transform\n    position {offset[0]:.8g} {offset[1]:.8g} {offset[2]:.8g}\n    scale {scale:.8g} {scale:.8g} {scale:.8g}\n  ModelRenderer\n    model Library/{asset["id"]}/model.gltf\n  Parent\n    entity "Display"\n')
    s += entity('Plinth', '  Transform\n    position 0 0.25 0\n    scale 3.6 0.5 3.6\n  MeshRenderer\n    mesh cube\n    tint 0.055 0.07 0.09 1\n    metallic 0.25\n    roughness 0.5\n  Parent\n    entity "Display"\n')
    s += entity('Index strip', '  Transform\n    position 0 0.35 1.81\n    scale 2.7 0.05 0.02\n  MeshRenderer\n    mesh cube\n    tint 0.04 0.6 0.8 1\n    emissive 0.04 0.6 0.8 1\n    emissive_intensity 2\n    cast_shadows 0\n  Parent\n    entity "Display"\n')
    path = PROJECT / 'Content/Prefabs' / (asset['id'] + '.swprefab')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(s)


def studio_hdr():
    path = PROJECT / 'Content/Studio/studio.hdr'
    path.parent.mkdir(parents=True, exist_ok=True)
    # Standard Radiance RGBE, uncompressed scanlines; procedural, no library image used.
    width, height = 256, 128
    data = bytearray(f'#?RADIANCE\nFORMAT=32-bit_rle_rgbe\n\n-Y {height} +X {width}\n'.encode())
    for y in range(height):
        for x in range(width):
            t = y / (height - 1)
            color = [0.12 + (1-t)*0.18, 0.15+(1-t)*0.22, 0.2+(1-t)*0.3]
            if (20 < x < 58 or 142 < x < 173) and 17 < y < 47:
                color = [7, 6.3, 5.7] if x < 100 else [3.5, 5, 7]
            m, exponent = math.frexp(max(color))
            factor = m * 256 / max(color)
            data.extend(bytes([min(255, int(c*factor)) for c in color] + [exponent+128]))
    path.write_bytes(data)


def scene(name, assets, count, columns, material=False):
    rows = math.ceil(count / columns)
    spacing = 5.2
    span = max(columns, rows) * spacing
    s = 'shockwave_scene 2\n\n# Generated by Tools/PrepareAssets.py; editable in Shockwave.\n\n'
    s += entity('Environment', f'  Environment\n    sky_color 0.16 0.21 0.3 1\n    ground_color 0.04 0.05 0.07 1\n    ambient_intensity 0.2\n    environment_map Studio/studio.hdr\n    environment_intensity 0.7\n    show_environment 0\n    exposure 0\n    shadow_distance {max(40, span*2):.3g}\n')
    s += entity('Floor', f'  Transform\n    position 0 -0.15 0\n    scale {span+10:.3g} 0.25 {span+10:.3g}\n  MeshRenderer\n    mesh cube\n    tint 0.12 0.15 0.19 1\n    roughness 0.5\n    metallic 0.15\n')
    camera = (span*0.55, span*0.8)
    s += entity('Lab Camera', f'  Transform\n    position 0 {camera[0]:.4g} {camera[1]:.4g}\n    rotation -34 0 0\n  Camera\n    fov 60\n    near_plane 0.1\n')
    s += entity('Key light', '  Transform\n    rotation -48 -30 0\n  Light\n    type Directional\n    color 1 0.91 0.8 1\n    intensity 3\n')
    for i in range(4 if material else 8):
        a = i * math.tau / (4 if material else 8)
        x,z = math.cos(a)*span*.45, math.sin(a)*span*.45
        color = '0.4 0.65 1 1' if i%2 else '1 0.65 0.35 1'
        s += entity(f'Fill {i}', f'  Transform\n    position {x:.3f} 4 {z:.3f}\n  Light\n    type Point\n    color {color}\n    intensity 18\n    range 12\n    cast_shadows 0\n')
    for i in range(count):
        asset = assets[i % len(assets)]
        x = (i%columns - (columns-1)/2)*spacing
        z = (i//columns - (rows-1)/2)*spacing
        s += entity(f'{asset["id"]} / {i+1:04}', f'  Prefab\n    path "Prefabs/{asset["id"]}.swprefab"\n  Transform\n    position {x:.3f} 0 {z:.3f}\n    rotation 0 {25 if material else ((i%4)*15)} 0\n')
    s += entity('Lab HUD', '  UIDocument\n    document UI/lab.rml\n    focus_on_show 0\n    preview "lab_stats=RENDER LAB; lab_quality=Use F1-F4 for quality presets; lab_scene='+name+'"\n')
    (PROJECT/'Scenes'/f'{name}.swscene').write_text(s)
    return {'scene': name, 'models': count, 'unique_models': len(set(assets[i%len(assets)]['id'] for i in range(count))),
            'source_triangles': sum(assets[i%len(assets)]['triangles'] for i in range(count))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--library', type=Path, required=True)
    parser.add_argument('--importer', type=Path, default=PROJECT.parents[1]/'build/bin/renderlab_import')
    parser.add_argument('--texture-size', type=int, default=2048, choices=[0, 512, 1024, 2048, 4096])
    parser.add_argument('--flip-normal-green', action='store_true', help='Use only for DirectX-convention source normal maps')
    args = parser.parse_args()
    if not args.library.is_dir() or not args.importer.is_file():
        parser.error('library folder and built renderlab_import executable must exist')
    sources = [(f'gun_{n:02}', args.library/'FBX - 30 Old Gun final'/str(n)/f'{n}.fbx', True) for n in GUNS]
    sources += [(name, args.library/'JRO_HardSurface_Kitbash_Vol.5/HSKitbash05_SingleParts/FBX'/f'{name}.fbx', False) for name in ENGINES]
    for _, path, _ in sources:
        if not path.is_file(): raise FileNotFoundError(path)
    report_folder = PROJECT/'Saved/Import'
    report_folder.mkdir(parents=True, exist_ok=True)
    assets = []
    for name, source, textured in sources:
        dest = PROJECT/'Content/Library'/name
        dest.mkdir(parents=True, exist_ok=True)
        maps = prepare_maps(source.parent, dest, args.texture_size, args.flip_normal_green) if textured else {}
        with (report_folder/f'{name}.log').open('w') as log:
            subprocess.run([str(args.importer.resolve()), str(source), str(dest/'model.gltf'), str(report_folder/f'{name}.json')],
                           stdout=log, stderr=log, check=True)
        item = json.loads((report_folder/f'{name}.json').read_text())
        item.update(id=name, source=str(source), source_sha256=digest(source), maps=maps,
                    converted_sha256=digest(dest/'geometry.bin'))
        item['prepared_files'] = []
        for file in sorted(dest.iterdir()):
            if not file.is_file(): continue
            entry = {'name':file.name,'bytes':file.stat().st_size,'sha256':digest(file)}
            if file.suffix == '.png':
                with Image.open(file) as image: entry['size'] = list(image.size)
            item['prepared_files'].append(entry)
        write_prefab(item)
        assets.append(item)
        print(f'{name}: {item["triangles"]:,} triangles, {item["meshes"]} parts, {item["textures"]} textures', flush=True)
    studio_hdr()
    scenes = [scene('gallery', assets,16,4), scene('materials', [assets[0],assets[2],assets[8],assets[12]],4,2,True)]
    scenes += [scene(f'stress-{n}', assets,n,math.isqrt(n)) for n in [64,256,1024]]
    manifest = {'texture_size_limit':args.texture_size, 'normal_green_flipped':args.flip_normal_green,
                'assets':assets, 'scenes':scenes}
    (PROJECT/'Saved/Import/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('Prepared',len(assets),'assets; report:',PROJECT/'Saved/Import/manifest.json')

if __name__ == '__main__':
    main()
